import streamlit as st
import numpy as np
from PIL import Image
import matplotlib.pyplot as plt

st.set_page_config(page_title="Linear Algebra Toolbox", layout="wide", page_icon="🧮")

st.title("🧮 Linear Algebra Toolbox")
st.markdown("Aplikasi interaktif untuk operasi Aljabar Linear (Diagonalisasi, Dekomposisi LU, Power Method, dan SVD).")

st.sidebar.header("Pilih Menu Operasi")
menu = st.sidebar.radio(
    "Pilih salah satu:",
    ("Diagonalisasi Matriks", "Dekomposisi LU", "Power Method", "SVD (Singular Value Decomposition)")
)

def input_matrix_ui(key_prefix):
    n = st.number_input("Ukuran matriks (n x n):", min_value=1, max_value=20, value=3, step=1, key=f"{key_prefix}_n")
    st.write("Masukkan elemen matriks (pisahkan kolom dengan spasi, baris baru untuk baris berikutnya):")

    # Generate default identity-like matrix structure for easy editing
    default_matrix = "\n".join([" ".join(["1" if i==j else "0" for j in range(n)]) for i in range(n)])
    matrix_text = st.text_area("Input Matriks", value=default_matrix, height=200, key=f"{key_prefix}_text")

    try:
        rows = matrix_text.strip().split("\n")
        if len(rows) != n:
            st.warning(f"Harap masukkan tepat {n} baris.")
            return None

        matrix = []
        for row in rows:
            elements = list(map(float, row.strip().split()))
            if len(elements) != n:
                st.error(f"Setiap baris harus memiliki tepat {n} elemen. Silakan periksa kembali spasi Anda.")
                return None
            matrix.append(elements)
        return np.array(matrix)
    except Exception as e:
        st.error(f"Input tidak valid: Pastikan Anda hanya memasukkan angka yang dipisah spasi.")
        return None

# --- 1. Diagonalisasi Matriks ---
if menu == "Diagonalisasi Matriks":
    st.header("Diagonalisasi Matriks")
    matrix = input_matrix_ui("diag")

    if st.button("Cek Diagonalisasi", type="primary") and matrix is not None:
        try:
            eigenvalues, eigenvectors = np.linalg.eig(matrix)
            unique_eigenvalues = set(np.round(eigenvalues, 5))

            is_diagonalizable = True
            for eigenvalue in unique_eigenvalues:
                # Algebraic multiplicity
                alg_mult = np.count_nonzero(np.isclose(np.round(eigenvalues, 5), eigenvalue))
                # Geometric multiplicity
                eigenspace = eigenvectors[:, np.isclose(np.round(eigenvalues, 5), eigenvalue)]
                geom_mult = np.linalg.matrix_rank(eigenspace)

                if alg_mult != geom_mult:
                    is_diagonalizable = False
                    break

            st.subheader("Hasil:")
            st.write("**Eigenvalues:**", eigenvalues)
            st.write("**Eigenvectors:**")
            st.dataframe(eigenvectors)

            if is_diagonalizable:
                st.success("Matriks ini **diagonalizable** (dapat didiagonalisasi).")
            else:
                st.error("Matriks ini **tidak diagonalizable**.")
        except Exception as e:
            st.error(f"Terjadi kesalahan komputasi: {e}")
# --- 2. Dekomposisi LU ---
elif menu == "Dekomposisi LU":
    st.header("Dekomposisi LU (Metode Doolittle)")
    matrix = input_matrix_ui("lu")

    if st.button("Hitung LU", type="primary") and matrix is not None:
        try:
            n = matrix.shape[0]
            L = np.zeros((n, n))
            U = np.zeros((n, n))

            singular = False
            for i in range(n):
                for k in range(i, n):
                    U[i][k] = matrix[i][k] - sum(L[i][j] * U[j][k] for j in range(i))

                for k in range(i, n):
                    if i == k:
                        L[i][i] = 1
                    else:
                        if U[i][i] == 0:
                            singular = True
                            break
                        L[k][i] = (matrix[k][i] - sum(L[k][j] * U[j][i] for j in range(i))) / U[i][i]
                if singular:
                    break

            if singular:
                st.error("Matriks singular! Tidak dapat didekomposisi dengan metode Doolittle.")
            else:
                st.subheader("Hasil Dekomposisi:")
                col1, col2 = st.columns(2)
                with col1:
                    st.write("**Lower Triangular Matrix (L):**")
                    st.dataframe(L)
                with col2:
                    st.write("**Upper Triangular Matrix (U):**")
                    st.dataframe(U)
        except Exception as e:
            st.error(f"Terjadi kesalahan: {e}")

# --- 3. Power Method ---
elif menu == "Power Method":
    st.header("Power Method (Dominant Eigenvalue)")
    matrix = input_matrix_ui("power")

    if st.button("Hitung Eigenvalue Dominan", type="primary") and matrix is not None:
        try:
            n = matrix.shape[0]
            x = np.ones(n)
            x = x / np.linalg.norm(x)
            eigenvalue_old = 0
            max_iter = 1000
            tolerance = 1e-6

            converged = False
            for i in range(max_iter):
                x_new = np.dot(matrix, x)
                x_new = x_new / np.linalg.norm(x_new)
                eigenvalue = np.dot(x_new, np.dot(matrix, x_new))

                if np.abs(eigenvalue - eigenvalue_old) < tolerance:
                    converged = True
                    st.success(f"Konvergen pada iterasi ke-{i+1}")
                    break

                eigenvalue_old = eigenvalue
                x = x_new

            if not converged:
                st.warning("Iterasi mencapai batas maksimum tanpa konvergensi.")

            st.subheader("Hasil:")
            st.write("**Dominant Eigenvalue:**", eigenvalue)
            st.write("**Dominant Eigenvector:**", x_new)
        except Exception as e:
            st.error(f"Terjadi kesalahan: {e}")

# --- 4. SVD ---
elif menu == "SVD (Singular Value Decomposition)":
    st.header("Singular Value Decomposition (SVD)")

    svd_mode = st.radio("Pilih Input Data:", ("Input Manual", "Upload Gambar"))

    if svd_mode == "Input Manual":
        matrix = input_matrix_ui("svd")
        if st.button("Hitung SVD", type="primary") and matrix is not None:
            try:
                U, S, VT = np.linalg.svd(matrix, full_matrices=False)
                st.subheader("Hasil SVD:")
                st.write("**Matriks U:**")
                st.dataframe(U)
                st.write("**Nilai Singular (Σ):**")
                st.dataframe(S)
                st.write("**Matriks V^T:**")
                st.dataframe(VT)
            except Exception as e:
                st.error(f"Terjadi kesalahan: {e}")

    elif svd_mode == "Upload Gambar":
        uploaded_file = st.file_uploader("Upload gambar (JPG, PNG)", type=["jpg", "png", "jpeg"])
        if uploaded_file is not None:
            image = Image.open(uploaded_file).convert("L")
            img_array = np.array(image).astype(float)

            col1, col2 = st.columns(2)
            with col1:
                st.image(image, caption="Gambar Asli (Grayscale)", use_column_width=True)

            # Compute SVD
            U, S, VT = np.linalg.svd(img_array, full_matrices=False)

            st.write("---")
            st.write("**Rekonstruksi Gambar dengan SVD**")
            k = st.slider("Pilih jumlah nilai singular untuk rekonstruksi (k):",
                          min_value=1, max_value=len(S), value=min(50, len(S)))

            S_reduced = np.zeros((U.shape[1], VT.shape[0]))
            S_reduced[:k, :k] = np.diag(S[:k])
            reconstructed = np.dot(U, np.dot(S_reduced, VT))

            reconstructed = np.clip(reconstructed, 0, 255).astype(np.uint8)
            with col2:
                st.image(reconstructed, caption=f"Gambar Rekonstruksi (k={k})", use_column_width=True)